-- ============================================
-- 062: LEAD COVER — one person works another person's book
-- ============================================
-- Dev, 2026-10-29: "there should be a sync between me and siddharth — he is
-- helping me manage and maintain all my leads."
--
-- Every work surface (Today queue, follow-ups due, escalations, the
-- notification feed and bell, the Pipeline board's "Mine" chip) is scoped on
-- crm_leads.assigned_to = you. So a person maintaining someone else's leads
-- could SEE them (RLS is team-wide) but was never TOLD about them: Dev's leads
-- going stale nagged only Dev, who is escalation-only. Nobody worked them.
--
-- A row here means: coverer_id is shown owner_id's leads on every work
-- surface, alongside their own.
--   * OWNERSHIP DOES NOT MOVE. assigned_to stays the owner's; the leads are
--     still the owner's book on the scoreboard (breach counts stay on the
--     owner's row and are not copied to the coverer — team totals sum only the
--     listed rows, and counting a lead twice would inflate them).
--   * CREDIT FOLLOWS THE WORK. Activity the coverer logs carries their
--     logged_by, so the scoreboard and digest credit them for it.
--   * NEVER DELETED. Ending cover stamps ended_at / ended_by; the row stays as
--     the record of who was covering whom and when (same lesson as
--     archived_by / settings updated_by). At most one OPEN row per pair.
--
-- Seeds the one pairing Dev asked for: Sidharth Zambre covers Dev. Matched by
-- email, not id, and inserted only if that pair has never had a row — so
-- re-running this after the cover is ended does not silently restart it.
--
-- RLS: any signed-in user may read (every work surface needs it); writes are
-- gated to admins at the route (Admin → All Users), same as crm_settings.
--
-- Safe to run multiple times.

CREATE TABLE IF NOT EXISTS crm_lead_cover (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  coverer_id INTEGER NOT NULL REFERENCES people(id),
  owner_id INTEGER NOT NULL REFERENCES people(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_by INTEGER REFERENCES people(id),
  ended_at TIMESTAMPTZ,
  ended_by INTEGER REFERENCES people(id)
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'crm_lead_cover_not_self'
  ) THEN
    ALTER TABLE crm_lead_cover
      ADD CONSTRAINT crm_lead_cover_not_self CHECK (coverer_id <> owner_id);
  END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_crm_lead_cover_open_pair
  ON crm_lead_cover (coverer_id, owner_id) WHERE ended_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_crm_lead_cover_coverer_open
  ON crm_lead_cover (coverer_id) WHERE ended_at IS NULL;

ALTER TABLE crm_lead_cover ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "team_can_view_lead_cover" ON crm_lead_cover;
CREATE POLICY "team_can_view_lead_cover" ON crm_lead_cover
  FOR SELECT TO authenticated USING (auth.uid() IS NOT NULL);

DROP POLICY IF EXISTS "team_can_create_lead_cover" ON crm_lead_cover;
CREATE POLICY "team_can_create_lead_cover" ON crm_lead_cover
  FOR INSERT TO authenticated WITH CHECK (auth.uid() IS NOT NULL);

DROP POLICY IF EXISTS "team_can_update_lead_cover" ON crm_lead_cover;
CREATE POLICY "team_can_update_lead_cover" ON crm_lead_cover
  FOR UPDATE TO authenticated USING (auth.uid() IS NOT NULL);

-- No DELETE policy, deliberately: cover is ended, never removed.

INSERT INTO crm_lead_cover (coverer_id, owner_id, created_by)
SELECT c.id, o.id, o.id
FROM people c, people o
WHERE lower(c.email) = 'sidharth@pocketfund.org'
  AND lower(o.email) = 'dev@pocket-fund.com'
  AND NOT EXISTS (
    SELECT 1 FROM crm_lead_cover x WHERE x.coverer_id = c.id AND x.owner_id = o.id
  );
